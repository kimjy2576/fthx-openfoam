"""
F1+F2 — OpenFOAM 케이스 디렉터리 생성 (blockMesh 배경격자 + snappyHexMesh)

1차 스코프: tutorial 급 형상만.
  · 벤드 없음 + 덕트 밀폐(sealed) + 관이 덕트 z 범위와 일치
  → 배경격자 = air_bbox, blockMesh 6면에 patch 이름을 직접 부여
    (Fluent 의 케이싱이 하던 일을 blockMesh 가 공짜로 해줌)
probe(벤드가 덕트 밖으로 나감)는 배경을 global_bbox 로 잡고 공기 외곽을
snappy 가 만들게 해야 하므로 별도 단계에서 확장함.

관벽 처리: Phase 2 는 A-lite — solid_tube 를 cellZone 으로 실제 메시.
  snappy 에는 Fluent 의 thin-volume 이 없어 관벽(t=0.65mm)에 셀을 넣으려면
  표면 level 을 t 미만 크기까지 올려야 함. 셀 증가를 감수하고 위상 검증을
  우선함. B안(baffle+thermalBaffle, 관벽 제거)은 Phase 3 에서 결정.

사이징: meshing.sizing() 의 값만 사용. 사람이 만질 값 없음.
  배경 h_bg = 2·h_air (Fluent 상·하류와 동일)
  level 1 = h_air (코어), level L_ref ≈ h_ref, level L_wall < t_wall
"""
