def _scale_stl(src: Path, dst: Path, f: float = 0.001) -> None:
    """binary STL 좌표 스케일 (mm→m). blockMesh 는 convertToMeters 로
    변환되지만 triSurface·eMesh·locationInMesh 는 변환되지 않으므로
    케이스에 들어가는 STL 은 m 단위여야 함 (실측: locationInMesh 단위
    불일치로 FATAL — 'Point ... is not inside the mesh')."""
    import numpy as np
    b = bytearray(src.read_bytes())
    n = int.from_bytes(b[80:84], "little")
    arr = np.frombuffer(b, dtype="<f4", count=n * 12 + 0, offset=84).copy() if False else None
    # 레코드 50B = 법선3f + 정점9f + attr2B → f4 view 는 불가(50 이 4의 배수 아님)
    import struct
    for i in range(n):
        off = 84 + i * 50
        vals = struct.unpack_from("<12f", b, off)
        struct.pack_into("<12f", b, off, *(v * f for v in vals))
    dst.write_bytes(bytes(b))

